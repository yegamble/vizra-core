package setup

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// edgeMarker starts the first line of every generated edge file. It carries
// the sha256 of the body below it, so an operator edit is detectable: a file
// whose body no longer matches is never overwritten without --yes.
const edgeMarker = "# GENERATED by vizra setup; sha256="

// Upstreams are the meta compose service names (docker-compose.yml: api
// listens on :8080, frontend on :3000).
const edgeRoutes = `	encode zstd gzip
	@api path /api/* /.well-known/*
	reverse_proxy @api api:8080
	reverse_proxy frontend:3000
`

// RenderEdge returns the edge file name and content for VIZRA_TLS_MODE:
// Caddyfile.local for acme/internal/plain-http (bind-mounted by the meta
// compose caddy service from ./deploy/Caddyfile.local) and nginx.example.conf
// for external (an example for the operator's own proxy; nothing mounts it).
func RenderEdge(env map[string]string) (string, string, error) {
	d := env["VIZRA_DOMAIN"]
	if !hostRe.MatchString(d) {
		return "", "", fmt.Errorf("VIZRA_DOMAIN %q is not a host name", d)
	}
	var name, body string
	switch env["VIZRA_TLS_MODE"] {
	case "acme":
		name, body = "Caddyfile.local", d+" {\n"+edgeRoutes+"}\n"
	case "internal":
		name, body = "Caddyfile.local", d+" {\n\ttls internal\n"+edgeRoutes+"}\n"
	case "plain-http":
		name, body = "Caddyfile.local", "# WARNING: plain HTTP. Sessions and passwords cross the network unencrypted.\n"+
			"# Use only on a trusted local network.\nhttp://"+d+" {\n"+edgeRoutes+"}\n"
	case "external":
		name, body = "nginx.example.conf", "# Example for VIZRA_TLS_MODE=external: your proxy terminates TLS.\n"+
			"# Publish api:8080 and frontend:3000 to this host (docker-compose.prod.yml) and adapt.\n"+
			"server {\n\tlisten 443 ssl;\n\tserver_name "+d+";\n\t# ssl_certificate /path/fullchain.pem;\n\t# ssl_certificate_key /path/privkey.pem;\n"+
			"\tclient_max_body_size 0;\n\tproxy_set_header Host $host;\n\tproxy_set_header X-Forwarded-Proto https;\n"+
			"\tproxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"+
			"\tlocation /api/ { proxy_pass http://127.0.0.1:8080; }\n\tlocation /.well-known/ { proxy_pass http://127.0.0.1:8080; }\n"+
			"\tlocation / { proxy_pass http://127.0.0.1:3000; }\n}\n"
	default:
		return "", "", fmt.Errorf("VIZRA_TLS_MODE %q: want acme, internal, plain-http or external", env["VIZRA_TLS_MODE"])
	}
	sum := sha256.Sum256([]byte(body))
	return name, edgeMarker + hex.EncodeToString(sum[:]) + "\n" + body, nil
}

// untouched reports whether content is a generated edge file whose body still
// matches its marker hash.
func untouched(content string) bool {
	first, body, ok := strings.Cut(content, "\n")
	if !ok || !strings.HasPrefix(first, edgeMarker) {
		return false
	}
	sum := sha256.Sum256([]byte(body))
	return strings.TrimPrefix(first, edgeMarker) == hex.EncodeToString(sum[:])
}

// WriteEdge renders the edge file into dir atomically (mode 0644: it holds no
// secrets and caddy reads it as a non-root user). An existing file that is
// not an untouched generated file is replaced only with yes.
func WriteEdge(dir string, env map[string]string, yes bool) (string, error) {
	name, out, err := RenderEdge(env)
	if err != nil {
		return "", err
	}
	p := filepath.Join(dir, name)
	if old, err := os.ReadFile(p); err == nil {
		if string(old) == out {
			return p, nil
		}
		if !untouched(string(old)) && !yes {
			return "", fmt.Errorf("%s was edited by hand; re-run with --yes to replace it", p)
		}
	} else if !os.IsNotExist(err) {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	tmp, err := os.CreateTemp(dir, "."+name+".*")
	if err != nil {
		return "", err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(out); err == nil {
		err = tmp.Chmod(0o644)
	}
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return "", err
	}
	return p, os.Rename(tmp.Name(), p)
}
